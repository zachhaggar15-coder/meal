import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { INDEXABLE_PLAN_SEEDS } from '../src/data/planSeeds.js';
import { getSeedMacroGrams } from '../src/utils/planBuilder.js';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(projectRoot, 'src', 'data', 'planMacroIndex.js');
const checkOnly = process.argv.includes('--check');

const index = Object.fromEntries(INDEXABLE_PLAN_SEEDS.map(seed => [
  seed.slug,
  getSeedMacroGrams(seed),
]));
const output = `// Generated by scripts/generate-plan-macro-index.js. Do not edit by hand.\n`
  + `export const PLAN_MACRO_INDEX = Object.freeze(${JSON.stringify(index, null, 2)});\n`;

if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    console.error('Plan macro index is stale. Run npm run generate:plan-macros.');
    process.exitCode = 1;
  } else {
    console.log(`Plan macro index is current (${INDEXABLE_PLAN_SEEDS.length} plans).`);
  }
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated actual macro data for ${INDEXABLE_PLAN_SEEDS.length} plans.`);
}
