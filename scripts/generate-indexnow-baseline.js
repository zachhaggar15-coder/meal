// Captures the IndexNow bootstrap baseline: what the site looked like before
// IndexNow was installed.
//
// The first production run of /api/indexnow-sync has no Redis snapshot to diff
// against. Without a baseline it can only record what is live and submit
// nothing, which silently absorbs any page that was created or materially
// changed in the same release that installed IndexNow. Diffing against this
// committed snapshot of the pre-install site closes that gap.
//
//   npm run generate:indexnow-baseline      # refuses to overwrite
//   npm run generate:indexnow-baseline -- --force
//
// This is a one-time artefact and must NOT be regenerated after IndexNow has
// shipped: a baseline captured from a later build would describe the new pages
// as already known, which is exactly what it exists to prevent. Once the first
// production run has stored a Redis snapshot the baseline is never read again.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { INDEXNOW_MANIFEST_FILENAME, manifestRoutes } from '../server/indexnow.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(root, 'dist', INDEXNOW_MANIFEST_FILENAME);
const outputPath = path.join(root, 'server', 'indexnow-baseline.js');
const force = process.argv.includes('--force');

if (!fs.existsSync(manifestPath)) {
  console.error(`generate-indexnow-baseline: ${manifestPath} not found. Run the build first.`);
  process.exit(1);
}

if (fs.existsSync(outputPath) && !force) {
  console.error(
    'generate-indexnow-baseline: a baseline already exists.\n'
    + 'It describes the site before IndexNow shipped and regenerating it would\n'
    + 'hide every page added since. Pass --force only if you are certain.',
  );
  process.exit(1);
}

const routes = manifestRoutes(JSON.parse(fs.readFileSync(manifestPath, 'utf8')));
if (!routes || !Object.keys(routes).length) {
  console.error('generate-indexnow-baseline: the manifest has no routes.');
  process.exit(1);
}

const commit = gitCommit();
const entries = Object.keys(routes)
  .sort()
  .map(route => `  ${JSON.stringify(route)}: ${JSON.stringify(routes[route])},`)
  .join('\n');

const file = `// Generated by scripts/generate-indexnow-baseline.js - do not edit by hand.
//
// The state of the site immediately before IndexNow was installed, used once by
// /api/indexnow-sync to work out what the installation release itself added or
// changed. See docs/indexnow.md; do not regenerate after IndexNow has shipped.
//
// Captured from: ${commit}
// Routes: ${Object.keys(routes).length}

export const INDEXNOW_BASELINE_COMMIT = ${JSON.stringify(commit)};

export const INDEXNOW_BASELINE_ROUTES = {
${entries}
};
`;

fs.writeFileSync(outputPath, file);
console.log(`IndexNow baseline written: ${Object.keys(routes).length} routes from ${commit} → server/indexnow-baseline.js`);

function gitCommit() {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}
