// Generates the blog -> plan pairing used by the blog email capture.
//
// Resolving a plan needs the whole catalogue, and those modules are ~190KB and
// ~120KB. Shipping them to blog readers to answer one question per page would
// tax the Core Web Vitals of the pages this capture exists to monetise, so the
// pairing is computed here and shipped as a small static index.
//
// Mirrors scripts/generate-plan-macro-index.js: --check fails the build when
// the committed index no longer matches the catalogue, so a plan being renamed
// or retired surfaces as a build failure rather than as an email the API
// cannot build.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { blogPostsData } from '../src/data/blogPosts.js';
import { SEO_EXACT_PLAN_LINKS } from '../src/data/seoOpportunityPages.js';
import { mealPlansData } from '../src/data/mealPlans.js';
import { getAllPlanMeta } from '../src/utils/planBuilder.js';
import { buildPlanIndex, resolveBlogPlanSlug } from '../src/utils/blogPlanMatch.js';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(projectRoot, 'src', 'data', 'blogPlanIndex.js');
const checkOnly = process.argv.includes('--check');

const planMeta = getAllPlanMeta();
const metaBySlug = new Map(planMeta.map(meta => [meta.slug, meta]));
const index = buildPlanIndex(planMeta);

// api/email-plan.js resolves generated plans first, then legacy ones. The index
// must not offer a slug that resolver would reject, so it is mirrored exactly.
const emailablePlans = new Set([
  ...metaBySlug.keys(),
  ...Object.keys(mealPlansData).filter(slug => mealPlansData[slug]?.plan?.length),
]);

function describe(planSlug) {
  const meta = metaBySlug.get(planSlug);
  if (meta) {
    return {
      planSlug,
      title: meta.title,
      supermarket: meta.supermarket,
      goal: meta.goal,
      goalLabel: meta.goalLabel,
      calories: meta.calories,
    };
  }
  const legacy = mealPlansData[planSlug];
  return {
    planSlug,
    title: legacy?.title || legacy?.h1 || 'Weekly meal plan',
    supermarket: null,
    goal: null,
    goalLabel: legacy?.planLabel || null,
    calories: legacy?.targetCalories ?? null,
  };
}

const entries = [];
const unresolved = [];
for (const slug of Object.keys(blogPostsData).sort()) {
  const planSlug = resolveBlogPlanSlug({
    slug,
    exactPlanLinks: SEO_EXACT_PLAN_LINKS[slug] || [],
    index,
    emailablePlans,
  });
  if (!planSlug) {
    unresolved.push(slug);
    continue;
  }
  entries.push([slug, describe(planSlug)]);
}

if (unresolved.length) {
  console.error(
    `${unresolved.length} blog post(s) resolved to no emailable plan:\n  ${unresolved.join('\n  ')}`,
  );
  process.exitCode = 1;
}

const output = '// Generated by scripts/generate-blog-plan-index.js. Do not edit by hand.\n'
  + `export const BLOG_PLAN_INDEX = Object.freeze(${JSON.stringify(Object.fromEntries(entries), null, 2)});\n`;

if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    console.error('Blog plan index is stale. Run npm run generate:blog-plan-index.');
    process.exitCode = 1;
  } else {
    console.log(`Blog plan index is current (${entries.length} posts).`);
  }
} else {
  fs.writeFileSync(outputPath, output);
  const supermarketMatched = entries.filter(([, v]) => v.supermarket && v.supermarket !== 'any').length;
  console.log(
    `Generated blog plan pairings for ${entries.length} posts `
    + `(${supermarketMatched} matched to a supermarket-specific plan).`,
  );
}
